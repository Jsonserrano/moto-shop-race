// Muestra como máximo 5 miniaturas repartidas entre todas las vistas
function indicesMiniaturas(total) {
    if (total <= 5) return [...Array(total).keys()];
    return [0, 1, 2, 3, 4].map(k => Math.round(k * (total - 1) / 4));
}

